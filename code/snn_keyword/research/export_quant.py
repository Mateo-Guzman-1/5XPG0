#!/usr/bin/env python3
"""Export QAT models as packed firmware headers + board test vectors (stage 1, step C).

For each requested bit width this writes, into research/results/quant/export_int<b>/:
    keyword_model.h     firmware header (same defines as Damien's, plus packed weights)
    board_vectors.npz   40 test clips + expected spike counts (benchmark_candidate_board.py format)
    export.json         seed, scales, metrics, bytes and the results of the checks below

The deployed firmware/keyword_model.h is NOT touched.

Seed selection: the seed with the best validation F1 at --select-bits (QAT runs in
qat.json); the test split is never used for the choice. The same seed is exported
at every bit width.

Packing of layer 1 (L = 32 / bits weights per 32-bit word):
    weight i of hidden neuron h  ->  word (h*128 + i) // L,  lane (h*128 + i) % L
    lane j occupies bits [j*bits, (j+1)*bits), two's complement, lane 0 = lowest bits.
The header also keeps the one-per-byte int8 array kw_w1, so every firmware variant
(packed or not) can run every model.

Checks (the script stops if one fails):
    1. unpacking every word the way the firmware will (shift left, arithmetic shift
       right, in 32 bits) gives back exactly the integer weights;
    2. re-scoring the exported integer model reproduces the qat.json threshold and
       validation/test metrics of that seed.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import torch

import frontend_sweep as sweep
import quant_sweep as qs


HERE = Path(__file__).resolve().parent


def pack(w: np.ndarray, bits: int) -> np.ndarray:
    lanes = 32 // bits
    flat = w.reshape(-1).astype(np.int64)
    if flat.size % lanes:
        raise ValueError("weight count is not a multiple of the lanes per word")
    fields = (flat & ((1 << bits) - 1)).reshape(-1, lanes)
    shifts = np.arange(lanes, dtype=np.int64) * bits
    return (fields << shifts).sum(axis=1).astype(np.uint32)


def unpack_like_firmware(words: np.ndarray, bits: int) -> np.ndarray:
    """(int32)(word << (32 - (j+1)*bits)) >> (32 - bits), as the C unpack loop."""
    lanes = 32 // bits
    out = []
    for j in range(lanes):
        shifted = (words.astype(np.uint64) << (32 - (j + 1) * bits)) & 0xFFFFFFFF
        out.append(shifted.astype(np.uint32).view(np.int32) >> (32 - bits))
    return np.stack(out, axis=1).reshape(-1)


def c_values(values: np.ndarray, per_line: int = 16, fmt: str = "{}") -> str:
    flat = [fmt.format(int(v)) for v in values.reshape(-1)]
    return "\n".join("    " + ", ".join(flat[i:i + per_line]) + ","
                     for i in range(0, len(flat), per_line))


def write_header(path: Path, q: dict, words: np.ndarray, cfg: sweep.FeatureConfig,
                 threshold: int, keyword: str, seed: int) -> None:
    bits = q["bits1"]
    unused = "__attribute__((unused))"
    text = f"""// Generated by research/export_quant.py (QAT, seed {seed}, layer-1 weights {bits} bit).
#ifndef KEYWORD_MODEL_H
#define KEYWORD_MODEL_H

#define KW_KEYWORD "{keyword}"
#define KW_INPUTS {cfg.inputs}
#define KW_HIDDEN {sweep.HIDDEN}
#define KW_OUTPUTS 2
#define KW_TIMESTEPS {sweep.TIMESTEPS}
#define KW_BETA_Q8 {qs.BETA_Q8}
#define KW_WEIGHT_SCALE {q["s1"]}
#define KW_WEIGHT_SCALE2 {q["s2"]}
#define KW_THRESHOLD1 {q["s1"] * 255}
#define KW_THRESHOLD2 {q["s2"]}
#define KW_DECISION_MARGIN {threshold}
#define KW_MIN_KEYWORD_SPIKES 0
#define KW_FEATURE_BITS {cfg.bits}
#define KW_FEATURE_BANDS {cfg.bands}
#define KW_FEATURE_TIME_BINS {sweep.TIME_BINS}
#define KW_FEATURE_LOW_HZ {cfg.low_hz}
#define KW_FEATURE_HIGH_HZ {cfg.high_hz}
#define KW_FEATURE_DURATION_MS {cfg.duration_ms}

// Layer-1 weight storage.
#define KW_WEIGHT_BITS {bits}
#define KW_W1_PER_WORD {32 // bits}
#define KW_W1_WORDS {words.size}

// One weight per byte (Damien's layout, used by the unpacked loop).
static const int8_t kw_w1[KW_HIDDEN * KW_INPUTS] {unused} = {{
{c_values(q["w1"])}
}};

// Packed: lane j of word k holds weight k*KW_W1_PER_WORD + j, lane 0 in the lowest bits.
static const uint32_t kw_w1_packed[KW_W1_WORDS] {unused} = {{
{c_values(words, 8, "0x{:08x}u")}
}};

static const int32_t kw_b1[KW_HIDDEN] = {{
{c_values(q["b1"], 8)}
}};

static const int8_t kw_w2[KW_OUTPUTS * KW_HIDDEN] = {{
{c_values(q["w2"])}
}};

static const int32_t kw_b2[KW_OUTPUTS] = {{
{c_values(q["b2"], 8)}
}};

#endif
"""
    path.write_text(text, encoding="ascii", newline="\n")


def main() -> int:
    snn = HERE.parent
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--qat-json", type=Path, default=HERE / "results/quant/qat.json")
    parser.add_argument("--bits", type=int, nargs="+", default=[8, 4])
    parser.add_argument("--select-bits", type=int, default=4)
    parser.add_argument("--dataset", type=Path, default=snn / "data/speech_commands_v2_sheila_subset")
    parser.add_argument("--keyword", default="sheila")
    parser.add_argument("--output-dir", type=Path, default=HERE / "results/quant")
    args = parser.parse_args()

    report = json.loads(args.qat_json.read_text(encoding="utf-8"))
    key = report["key"]
    qat_runs = [run for run in report["runs"] if run["method"] == "qat"]
    candidates = [run for run in qat_runs if run["bits_w1"] == args.select_bits]
    chosen = max(candidates, key=lambda run: (run["validation"]["f1"],
                                              run["validation"]["accuracy"], -run["seed"]))
    seed = chosen["seed"]
    print("validation F1 at", args.select_bits, "bit:",
          {run["seed"]: round(run["validation"]["f1"], 4) for run in candidates},
          "-> seed", seed)

    original = torch.load(Path(report["checkpoints"]) / f"{key}_seed{seed}.pt",
                          map_location="cpu", weights_only=True)
    cfg = sweep.FeatureConfig(**original["run"]["config"])
    x = np.load(snn / f"data/frontend_sweep_cache_sheila_v2/{key}.npy", mmap_mode="r")
    paths, y, speakers = sweep.discover_dataset(args.dataset, args.keyword)
    split = sweep.dataset_split(args.dataset, paths, speakers)
    val_index, test_index = np.flatnonzero(split == "val"), np.flatnonzero(split == "test")
    positive = test_index[y[test_index] == 1][:20]
    negative = test_index[y[test_index] == 0][:20]
    vector_index = np.r_[positive, negative]

    for bits in args.bits:
        run = next(r for r in qat_runs if r["seed"] == seed and r["bits_w1"] == bits)
        state = torch.load(Path(args.qat_json.parent) / f"{args.qat_json.stem}_models"
                           / f"{key}_seed{seed}_qat{bits}.pt", map_location="cpu", weights_only=True)
        q = qs.quantize(state, bits, run["bits_w2"], s1=run["scale_w1"], s2=run["scale_w2"])

        words = pack(q["w1"], bits)
        if not np.array_equal(unpack_like_firmware(words, bits), q["w1"].reshape(-1)):
            raise SystemExit(f"{bits} bit: unpack check FAILED")

        rescored = qs.evaluate(q, x, y, val_index, test_index, np.zeros(len(test_index), bool))
        for field in ("threshold", "validation", "test"):
            if rescored[field] != run[field]:
                raise SystemExit(f"{bits} bit: re-score does not match qat.json ({field})")

        counts, _ = qs.integer_counts(q, x[vector_index])
        out = args.output_dir / f"export_int{bits}"
        out.mkdir(parents=True, exist_ok=True)
        write_header(out / "keyword_model.h", q, words, cfg, rescored["threshold"], args.keyword, seed)
        np.savez_compressed(
            out / "board_vectors.npz",
            x=np.rint(np.asarray(x[vector_index]) * 255).astype(np.uint8),
            y=y[vector_index], counts=counts,
            paths=np.array([str(paths[i]) for i in vector_index]),
        )
        info = {
            "source": str(args.qat_json), "seed": seed,
            "seed_selection": f"best validation F1 of QAT runs at {args.select_bits} bit",
            "bits_w1": bits, "bits_w2": run["bits_w2"],
            "scale_w1": q["s1"], "scale_w2": q["s2"],
            "threshold1": q["s1"] * 255, "threshold2": q["s2"],
            "decision_threshold": rescored["threshold"],
            "w1_range": rescored["w1_range"],
            "w1_words": int(words.size),
            "bytes": rescored["bytes"],
            "integer_validation": rescored["validation"],
            "integer_test": rescored["test"],
            "checks": {"unpack_matches_weights": True, "rescore_matches_qat_json": True},
            "vectors": int(len(vector_index)),
            "vector_spikes_keyword_class": int(counts[:, 1].sum()),
        }
        (out / "export.json").write_text(json.dumps(info, indent=2), encoding="utf-8")
        print(f"{bits} bit: scale {q['s1']}, weights {rescored['w1_range']}, "
              f"{words.size} words, {rescored['bytes']['total']} B, "
              f"test acc {100 * rescored['test']['accuracy']:.2f} %, checks OK -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
